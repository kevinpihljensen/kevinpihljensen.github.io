// build-singlefile.mjs
// Produces `fps-standalone.html`: ONE file, no server, no GitHub needed.
// Double-click it and it runs from file://.
//
// How it works:
//  1. Concatenate every src/*.js module in dependency order.
//  2. Strip the inter-module `import {...} from './x.js'` lines and the
//     `export ` keyword (everything ends up in one shared scope, so the
//     names just resolve directly — no module boundary needed).
//  3. Keep the bare `import * as THREE from 'three'` working by injecting an
//     importmap (data-URI) — but for file:// we instead inline THREE from a
//     fetched copy is not allowed offline, so we keep the unpkg URL: it still
//     works from file:// because it's an absolute https URL, not a relative
//     module path. (Only RELATIVE module fetches are blocked on file://.)
//  4. Base64-embed every assets/audio/*.wav and rewrite audio.js's fetch()
//     paths to those data: URIs so audio works with no network/server.
//
// The modular source under src/ stays the source of truth; this is a
// generated artifact. Re-run after any code change:  node build-singlefile.mjs

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join } from 'path';

const ROOT = '.';
const SRC = join(ROOT, 'src');

// Dependency order: leaves first, main last. Mirrors the real import graph.
const ORDER = [
  'constants.js',
  'state.js',
  'scene.js',
  'audio.js',
  'collision.js',
  'textures.js',
  'kit.js',
  'maplayout.js',
  'arena.js',
  'decals.js',
  'projectiles.js',
  'enemies.js',
  'weapons.js',
  'player.js',
  'wave.js',
  'hud.js',
  'input.js',
  'main.js',
];

// --- 1. Embed audio as base64 data URIs -----------------------------------
const audioDir = join(ROOT, 'assets', 'audio');
const wavs = readdirSync(audioDir).filter(f => f.endsWith('.wav'));
const audioMap = {};
for (const f of wavs) {
  const b64 = readFileSync(join(audioDir, f)).toString('base64');
  audioMap[f] = `data:audio/wav;base64,${b64}`;
}

// --- 2. Read + transform each module --------------------------------------
function stripModule(code) {
  return code
    // drop relative imports entirely:  import {...} from './x.js';
    .replace(/^\s*import\s+[^;]*?\s+from\s+['"]\.\/[^'"]+['"]\s*;?\s*$/gm, '')
    // drop bare side-effect relative imports:  import './x.js';
    .replace(/^\s*import\s+['"]\.\/[^'"]+['"]\s*;?\s*$/gm, '')
    // keep `import * as THREE from 'three'` ONLY in the first module that has
    // it; we’ll handle THREE separately below. Strip all of them here and
    // re-add a single one at the top of the bundle.
    .replace(/^\s*import\s+\*\s+as\s+THREE\s+from\s+['"]three['"]\s*;?\s*$/gm, '')
    // turn `export function/const/let/class` into plain declarations
    .replace(/^\s*export\s+(default\s+)?/gm, '')
    // drop standalone `export { ... };` re-export lines
    .replace(/^\s*export\s*\{[^}]*\}\s*;?\s*$/gm, '');
}

let bundle = `// === FPS standalone bundle (generated by build-singlefile.mjs) ===\n`;
bundle += `import * as THREE from 'three';\n\n`;

for (const name of ORDER) {
  const raw = readFileSync(join(SRC, name), 'utf8');
  let code = stripModule(raw);
  if (name === 'audio.js') {
    // Rewrite the SAMPLE_FILES map values to data: URIs. The map entries look
    // like  pistol: 'assets/audio/pistol.wav',
    code = code.replace(/(['"])assets\/audio\/([A-Za-z0-9_]+\.wav)\1/g,
      (m, q, file) => {
        const uri = audioMap[file];
        if (!uri) return m;
        return JSON.stringify(uri);
      });
  }
  bundle += `\n// ---------- ${name} ----------\n` + code + '\n';
}

// --- 3. Splice into the HTML shell ----------------------------------------
let html = readFileSync(join(ROOT, 'index.html'), 'utf8');

// Replace the external module script tag with an inline module containing the
// whole bundle. Keep the importmap (THREE still loads from its https URL,
// which is allowed even on file://).
html = html.replace(
  /<script\s+type="module"\s+src="src\/main\.js"><\/script>/,
  () => `<script type="module">\n${bundle}\n</script>`
);

// Swap the “needs a server” comment for a “double-click me” note.
html = html.replace(
  /<!--[\s\S]*?-->/,
  () => `<!--
    STANDALONE BUILD — no server required.
    Just double-click this file (opens via file://) and it runs.
    Needs an internet connection on first load (Three.js is fetched from
    its CDN). Everything else (code + audio) is embedded in this file.
    Generated by build-singlefile.mjs from the modular src/ tree.
  -->`
);

writeFileSync(join(ROOT, 'fps-standalone.html'), html);
const kb = (Buffer.byteLength(html) / 1024).toFixed(0);
console.log(`wrote fps-standalone.html (${kb} KB, ${wavs.length} audio files embedded)`);
